// - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -
double SpeakJetTables::speedFactor(uInt8 speed)
{
  return ourSpeedFactor[std::min<size_t>(speed, ourSpeedFactor.size() - 1)];
}

// - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -
double SpeakJetTables::pitchFactor(uInt8 pitch)
{
  // Pitch 0 still voices, at no fundamental that can be pinned down
  if(pitch == 0)
    return 1.0;

  return DBL(pitch) / DBL(SpeakJet::DEFAULT_PITCH);
}

// - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -
double SpeakJetTables::pitchGain(uInt8 pitch, uInt8 atPitch)
{
  return std::pow(pitchFactor(pitch) / pitchFactor(atPitch), PITCH_POWER_EXP / 2);
}

// - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -
double SpeakJetTables::pitchDuration(uInt8 pitch)
{
  // Below the table the length is left alone; there the codes scatter as
  // much as the effect
  if(pitch < ourPitchKnot.front())
    return 1.0;

  for(size_t i = 1; i < ourPitchKnot.size(); ++i)
    if(pitch <= ourPitchKnot[i])
    {
      const double at = DBL(pitch - ourPitchKnot[i - 1]) /
                        DBL(ourPitchKnot[i] - ourPitchKnot[i - 1]);

      return std::lerp(DBL(ourPitchDuration[i - 1]), DBL(ourPitchDuration[i]), at);
    }

  return ourPitchDuration.back();
}

// - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -
double SpeakJetTables::phraseDuration(uInt8 pitch)
{
  const double law = pitchDuration(pitch);
  return pitch > SpeakJet::DEFAULT_PITCH ? 1.0 + (law - 1.0) * PHRASE_KEPT : law;
}

// - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -
double SpeakJetTables::volumeFactor(uInt8 volume)
{
  const double here = VOLUME_SLOPE * DBL(volume) + VOLUME_OFFSET;
  const double ref = VOLUME_SLOPE * DBL(SpeakJet::DEFAULT_VOLUME) + VOLUME_OFFSET;

  return std::max(0.0, here / ref);
}

// - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -
double SpeakJetTables::fixedMs(uInt8 code)
{
  return DBL(ourFixedMs[code - SpeakJet::FIRST_SOUND]);
}

// - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -
double SpeakJetTables::joinMs(uInt8 from, uInt8 to)
{
  const auto a = SZT(from - SpeakJet::FIRST_SOUND);
  const auto b = SZT(to - SpeakJet::FIRST_SOUND);

  // The pair itself where it was measured, otherwise the per-code tables
  const Int16 measured =
      (from <= SpeakJet::LAST_ALLOPHONE && to <= SpeakJet::LAST_ALLOPHONE)
        ? ourPairJoin[a][b] : NO_PAIR;

  return measured != NO_PAIR ? DBL(measured)
       : (a == b) ? DBL(ourMergeMs[a])
                  : DBL(ourJoinOut[a]) + DBL(ourJoinIn[b]);
}

// - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -
std::optional<double> SpeakJetTables::repeatMs(uInt8 code)
{
  const Int16 ms = ourRepeatMs[code - SpeakJet::FIRST_SOUND];
  return ms != NO_PAIR ? std::optional<double>{DBL(ms)} : std::nullopt;
}

// - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - - -
bool SpeakJetTables::holdsRepeat(uInt8 code)
{
  const Int16 onsets = ourRepeatOnsets[code - SpeakJet::FIRST_SOUND];
  return onsets != NO_PAIR && onsets < HOLD_ONSETS;
}

